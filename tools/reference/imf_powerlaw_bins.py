"""Reference integrals of power-law IMF bins for tests/physics/test_opensps_imf.f90.

Writes tests/data/imf_powerlaw_bins.txt: one bin per line, `alpha lo hi integral`, where
integral = int_lo^hi m**(-alpha) dm, evaluated with Python's decimal module at 60 significant
digits (independent of the Fortran under test: another language, arbitrary precision). alpha,
lo and hi are written as round-trip doubles (repr), so the test reads exactly the numbers the
reference used; the integral is rounded to 25 significant digits.

The bins are the situations that break a bin weight computed as (hi**e - lo**e) / e, e = 1 - alpha:
narrow bins (relative widths down to 1e-14: the two powers cancel), slopes near 1 (e -> 0: a
cancellation divided by a small e), extreme slopes and masses (0.08 to 300 M_sun, alpha 0.3 to 5),
wide bins (up to a factor 10), and bins on either side of |e ln(hi / lo)| = 1/4, where
imf_bin_weights_tab switches between its series and exp(y) - 1.

Usage: python3 tools/reference/imf_powerlaw_bins.py > tests/data/imf_powerlaw_bins.txt
"""
import math
from decimal import Decimal, getcontext

getcontext().prec = 60

MASSES = [0.08, 0.1, 1.0, 10.0, 100.0, 300.0]
WIDTHS = [1e-14, 1e-12, 1e-9, 1e-6, 1e-3, 0.1, 1.0, 9.0]
ALPHAS = [0.3, 1.0 - 1e-6, 1.0, 1.0 + 1e-9, 1.0 + 1e-6, 1.35, 2.35, 3.5, 5.0]


def integral(alpha, lo, hi):
    a, l, h = Decimal(alpha), Decimal(lo), Decimal(hi)
    e = 1 - a
    if e == 0:
        return (h / l).ln()
    return ((e * h.ln()).exp() - (e * l.ln()).exp()) / e


def main():
    rows = []
    for alpha in ALPHAS:
        for m in MASSES:
            for w in WIDTHS:
                hi = m * (1.0 + w)
                if hi > m:
                    rows.append((alpha, m, hi))
    # Either side of the series switch: |e| ln(hi / lo) = 0.25 * (1 -+ 1e-9)
    for alpha in (0.3, 2.35, 5.0):
        e = abs(1.0 - alpha)
        for f in (1.0 - 1e-9, 1.0 + 1e-9):
            for m in (0.1, 10.0):
                rows.append((alpha, m, m * math.exp(0.25 * f / e)))
    print("# alpha lo hi integral(m**-alpha, lo, hi): generated by tools/reference/imf_powerlaw_bins.py")
    print(len(rows))
    for alpha, lo, hi in rows:
        print(f"{alpha!r} {lo!r} {hi!r} {integral(alpha, lo, hi):.25E}")


if __name__ == "__main__":
    main()
